const SHA = "a".repeat(40), BASE = "b".repeat(40), REVISION = "c".repeat(64)
const RUN_ID = "R".repeat(43)
const ISSUE = "2026-11-10T06:00:00.000Z"
const NOW = "2026-11-10T06:03:00.000Z"
const EXPIRY = "2026-11-10T06:10:00.000Z"
/** Construct a 32-hex-byte synthetic nonce. */
const stamp = n => n.toString(16).padStart(32, "0")
/** Verify fail-closed errors by exact code, not arbitrary rejection. */
const errorCode = code => e => e instanceof OfflineClaimLedgerError && e.code === code

/** Build strictly valid Phase 1B dispatch metadata for offline disk tests. */
function request(overrides = {}) {
  return {
    kind: "dispatch-request", schemaVersion: 1, requestId: stamp(1), runId: RUN_ID,
    expectedVersion: 9, projectId: "rivora", branch: "ppo/rivora/test",
    baseSha: BASE, headSha: SHA, capability: "implementation.backend", workerId: "codex",
    taskSource: { kind: "linear-issue", issueId: "RIC-144", revisionHash: REVISION },
    scope: { mode: "implementation", allowedPaths: ["local-operator/"], permits: ["workspace.read", "workspace.write"] },
    approval: { ownerId: "owner", approvalId: stamp(2), approvedAt: ISSUE },
    nonce: stamp(3), idempotencyKey: "d".repeat(64),
    issuedAt: ISSUE, expiresAt: EXPIRY, maxDurationMs: 120000, ...overrides
  }
}
/** Bind a claim to the exact signature-verified request digest and expected host. */
function claim(p, overrides = {}) {
  return {
    kind: "worker-claim", schemaVersion: 1, requestId: p.requestId,
    requestHash: remotePayloadDigest(p), runId: p.runId, expectedVersion: p.expectedVersion,
    workerId: p.workerId, hostId: "trusted-mac", claimNonce: stamp(4),
    claimedAt: "2026-11-10T06:02:00.000Z", leaseExpiresAt: "2026-11-10T06:04:00.000Z",
    ...overrides
  }
}
/** Isolate each fixture's local store and PPO run snapshot; no external services. */
async function setup(t, options = {}) {
  const storeDir = await realpath(await mkdtemp(join(tmpdir(), "ppo-1c-ledger-")))
  t.after(async () => { await rm(storeDir, { recursive: true, force: true }) })
  const coordinator = generateKeyPairSync("ed25519")
  const worker = generateKeyPairSync("ed25519")
  const p = request()
  let run = { runId: p.runId, version: p.expectedVersion, status: "implementation_in_progress",
    project: { id: p.projectId }, branch: p.branch, baseSha: p.baseSha,
    headSha: p.headSha, role: p.capability }
  let now = NOW
  const cfg = () => ({ mode: "offline-durable-proof-only", storeDir, now: () => now,
    coordinatorPublicKey: coordinator.publicKey, readRun: async () => structuredClone(run),
    resolveRole: actual => actual.role, approvedProjects: ["rivora"],
    workerRegistry: { codex: { hostId: "trusted-mac", online: options.online !== false,
      publicKey: worker.publicKey } } })
  /** Build a coordinator-signed request with the fixture key. */
  const signed = () => signRemoteEnvelope(p, "ppo-control-plane", coordinator.privateKey)
  /** Build a worker-signed claim with optional adversarial fields. */
  const signedClaim = (fields = {}) => signRemoteEnvelope(claim(p, fields), "codex", worker.privateKey)
  return { storeDir, coordinator, worker, p, cfg, signed, signedClaim,
    ledger: createOfflineDurableClaimLedger(cfg()), setRun: next => { run = next },
    setNow: next => { now = next }, getRun: () => run }
}

/** Read the on-disk digest-shaped reservation directory generated by the module. */
async function reservationDir(f) {
  const { readdir } = await import("node:fs/promises")
  const dirs = (await readdir(f.storeDir)).filter(n => n.startsWith("run-"))
  assert.equal(dirs.length, 1)
  return join(f.storeDir, dirs[0])
}

test("reserve and claim persist across a fresh ledger instance without authorizing execution", async t => {
  const f = await setup(t)
  const reserved = await f.ledger.reserve(f.signed())
  assert.equal(reserved.outcome, "reserved")
  assert.equal(reserved.releaseAuthorized, false)
  const c = claim(f.p)
  const signed = f.signedClaim()
  const claimed = await f.ledger.claim(f.p.runId, f.p.expectedVersion, signed)
  assert.equal(claimed.outcome, "claimed")
  assert.equal(claimed.releaseAuthorized, false)
  const restarted = createOfflineDurableClaimLedger(f.cfg())
  const fence = await restarted.checkFence(f.p.runId, f.p.expectedVersion, remotePayloadDigest(c))
  assert.equal(fence.current, true)
  assert.equal(fence.releaseAuthorized, false)
  assert.equal(fence.canExecute, false)
  await assert.rejects(restarted.reserve(f.signed()), errorCode("LEDGER_RUN_RESERVED"))
  await assert.rejects(restarted.claim(f.p.runId, f.p.expectedVersion,
    f.signedClaim({ claimNonce: stamp(7) })), errorCode("LEDGER_ALREADY_CLAIMED"))
  // A duplicate must not leave a pending marker that blocks a legitimate claim.
  assert.equal((await restarted.checkFence(f.p.runId, f.p.expectedVersion,
    remotePayloadDigest(c))).current, true)
  assert.equal((await restarted.inspect(f.p.runId, f.p.expectedVersion)).reserved, true)
})

