test("two separate Node processes cannot reserve the same run version", async t => {
  const f = await setup(t)
  const modulePath = fileURLToPath(new URL("./software-factory-remote-durable-ledger.mjs", import.meta.url))
  const script = `
    import { createPublicKey } from "node:crypto";
    import { pathToFileURL } from "node:url";
    const { createOfflineDurableClaimLedger } = await import(pathToFileURL(process.argv[1]).href);
    const input = JSON.parse(process.argv[2]);
    const ledger = createOfflineDurableClaimLedger({
      mode:"offline-durable-proof-only",storeDir:input.storeDir,
      now:()=>"2026-11-10T06:03:00.000Z",
      coordinatorPublicKey:createPublicKey(input.publicKey),
      readRun:async()=>input.run,resolveRole:run=>run.role,
      approvedProjects:["rivora"],workerRegistry:{}
    });
    try { const r=await ledger.reserve(input.signed); console.log(JSON.stringify({ok:true,outcome:r.outcome})); }
    catch(e){ console.log(JSON.stringify({ok:false,code:e.code})); }
  `
  const config = JSON.stringify({ storeDir: f.storeDir,
    publicKey: f.coordinator.publicKey.export({ type: "spki", format: "pem" }),
    run: f.getRun(), signed: f.signed() })
  const child = () => new Promise((resolve, reject) => {
    const proc = spawn(process.execPath, ["--input-type=module", "--eval", script, modulePath, config],
      { stdio: ["ignore", "pipe", "pipe"] })
    let stdout = "", stderr = ""
    proc.stdout.on("data", b => { stdout += b })
    proc.stderr.on("data", b => { stderr += b })
    proc.on("error", reject)
    proc.on("close", code => code === 0 ? resolve(JSON.parse(stdout.trim())) : reject(new Error(stderr)))
  })
  const results = await Promise.all([child(), child()])
  assert.equal(results.filter(r => r.ok).length, 1)
  assert.equal(results.filter(r => r.code === "LEDGER_RUN_RESERVED").length, 1)
})