test("global request nonce, approval and idempotency keys survive restart", async t => {
  for (const field of ["nonce", "approval", "idempotencyKey"]) {
    const f = await setup(t)
    await f.ledger.reserve(f.signed())
    const nextId = "S".repeat(43)
    const newRun = { ...f.getRun(), runId: nextId }
    f.setRun(newRun)
    let altered = { ...f.p, runId: nextId, requestId: stamp(202), nonce: stamp(203),
      idempotencyKey: "f".repeat(64), approval: { ...f.p.approval, approvalId: stamp(204) } }
    if (field === "nonce") altered.nonce = f.p.nonce
    else if (field === "approval") altered.approval.approvalId = f.p.approval.approvalId
    else altered.idempotencyKey = f.p.idempotencyKey
    const signed = signRemoteEnvelope(altered, "ppo-control-plane", f.coordinator.privateKey)
    await assert.rejects(createOfflineDurableClaimLedger(f.cfg()).reserve(signed),
      errorCode("LEDGER_REPLAY"), field)
  }
})

